def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = [
        Path("C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf"),
        Path("C:/Windows/Fonts/calibrib.ttf" if bold else "C:/Windows/Fonts/calibri.ttf"),
    ]
    for candidate in candidates:
        if candidate.exists():
            return ImageFont.truetype(str(candidate), size)
    return ImageFont.load_default()


def wrap(draw: ImageDraw.ImageDraw, text: str, max_width: int, fnt: ImageFont.ImageFont) -> list[str]:
    lines: list[str] = []
    for paragraph in text.split("\n"):
        words = paragraph.split()
        current = ""
        for word in words:
            trial = f"{current} {word}".strip()
            if draw.textbbox((0, 0), trial, font=fnt)[2] <= max_width:
                current = trial
            else:
                if current:
                    lines.append(current)
                current = word
        if current:
            lines.append(current)
    return lines


def rounded_box(draw: ImageDraw.ImageDraw, xy, title: str, body: str, fill: str, outline: str) -> None:
    x1, y1, x2, y2 = xy
    draw.rounded_rectangle(xy, radius=18, fill=fill, outline=outline, width=3)
    title_font = font(28, True)
    body_font = font(20)
    draw.text((x1 + 24, y1 + 20), title, fill="#102033", font=title_font)
    y = y1 + 62
    for line in wrap(draw, body, x2 - x1 - 48, body_font):
        draw.text((x1 + 24, y), line, fill="#334155", font=body_font)
        y += 28


def arrow(draw: ImageDraw.ImageDraw, start: tuple[int, int], end: tuple[int, int], label: str = "") -> None:
    draw.line([start, end], fill="#1f2937", width=4)
    sx, sy = start
    ex, ey = end
    if ex >= sx:
        head = [(ex, ey), (ex - 16, ey - 9), (ex - 16, ey + 9)]
    else:
        head = [(ex, ey), (ex + 16, ey - 9), (ex + 16, ey + 9)]
    draw.polygon(head, fill="#1f2937")
    if label:
        label_font = font(18)
        mx, my = (sx + ex) // 2, (sy + ey) // 2
        w = draw.textbbox((0, 0), label, font=label_font)[2]
        draw.rounded_rectangle((mx - w // 2 - 8, my - 20, mx + w // 2 + 8, my + 10), radius=7, fill="#ffffff")
        draw.text((mx - w // 2, my - 17), label, fill="#1f2937", font=label_font)


