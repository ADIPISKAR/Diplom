def paragraph_text(paragraph) -> str:
    return "".join(run.text for run in paragraph.runs).strip()


def find_section_bounds(doc: Document) -> tuple[int, int]:
    start = end = None
    for i, p in enumerate(doc.paragraphs):
        text = paragraph_text(p)
        if start is None and text == "3. Программная реализация веб-приложения аренды зарядных устройств":
            start = i
        elif start is not None and text.startswith("4. Описание интерфейса"):
            end = i
            break
    if start is None or end is None:
        raise RuntimeError("Не удалось найти границы глав 3.1-3.3")
    return start, end


def remove_paragraph(paragraph) -> None:
    element = paragraph._element
    element.getparent().remove(element)


def remove_table(table) -> None:
    element = table._element
    element.getparent().remove(element)


def remove_blocks_between(doc: Document, start_idx: int, end_idx: int) -> None:
    body = doc._body._element
    start_el = doc.paragraphs[start_idx]._element
    end_el = doc.paragraphs[end_idx]._element
    removing = False
    for child in list(body):
        if child is start_el:
            removing = True
            continue
        if child is end_el:
            break
        if removing:
            body.remove(child)


def append_after(paragraph, new_element) -> None:
    paragraph._element.addnext(new_element)


def add_after(paragraph, text: str = "", style: str | None = None):
    new_p = OxmlElement("w:p")
    paragraph._element.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if style:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


